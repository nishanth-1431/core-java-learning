public class HelloWorld {
    public static void main(String[] args) {
        // Variables are like boxes that hold data
        String message = "Hello, Nishanth! Welcome to Java.";
        int myAge = 25;
        double luckynumber = 3.14;

        // System.out.println prints whatever is inside to the screen
        System.out.println(message);
        System.out.println("My age is: " + myAge);
        System.out.println("lucky number is" + luckynumber);
    }
}
